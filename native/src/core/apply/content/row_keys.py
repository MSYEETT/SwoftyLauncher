#!/usr/bin/env python3
"""Write row_keys.inc: the row keys of the tables the content registries copy rows in, per row shape, from the
launcher's packages/core/src/activation/row_keys.txt.gz (the same lines: `@shape`, then its keys; `+word` is a nested
table). Run it after that file changes."""

import gzip
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[4] / "packages" / "core" / "src" / "activation" / "row_keys.txt.gz"
ROOTS = ["audio.audio_bundle_settings.audio_bundle_settings_N", "car_setup.presets.vehicle_package_setups_N",
         "entrants.entrant_lists.entrant_list_N", "entrants.entrant_lists.entrants.entrant_N",
         "entrants.standings.standings_N", "entrants.vehicles.vehicle_N",
         "entrants.vehicles.vehicle_packages.vehicle_package_N", "game_setup.scenarios.scenario_N",
         "options_system.options.multiplayer.options_folder_N.option_N.value_N"]


def main():
    shapes, current = {}, None
    for line in gzip.decompress(SOURCE.read_bytes()).decode().splitlines():
        if not line or line.startswith("#"):
            continue
        if line.startswith("@"):
            current = shapes.setdefault(line[1:], [])
        elif current is not None:
            current.append(line)
    keep = sorted(s for s in shapes if any(s == r or s.startswith(r + ".") for r in ROOTS))
    missing = [r for r in ROOTS if r not in shapes]
    if missing:
        raise SystemExit(f"row_keys.txt.gz has no {', '.join(missing)}")
    body = "\n".join(f"@{s}\n" + "\n".join(shapes[s]) for s in keep)
    chunks = [body[i:i + 8000] for i in range(0, len(body), 8000)]
    out = ["// Generated by row_keys.py from packages/core/src/activation/row_keys.txt.gz. Do not edit by hand.",
           "inline constexpr const char *ROW_KEYS[] = {"]
    out += [f'    R"keys({c})keys",' for c in chunks]
    out.append("};")
    (HERE / "row_keys.inc").write_text("\n".join(out) + "\n")
    print(f"row_keys.inc: {len(keep)} shapes, {sum(len(shapes[s]) for s in keep)} keys")


if __name__ == "__main__":
    main()
